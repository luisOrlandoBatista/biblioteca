CREATE TABLE refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL UNIQUE,   -- SHA-256 en hexadecimal: 64 caracteres
    usuario_id BIGINT      NOT NULL REFERENCES usuarios(id),
    familia    VARCHAR(36) NOT NULL,          -- un UUID por cada login
    expira_en  TIMESTAMP   NOT NULL,
    revocado   BOOLEAN     NOT NULL DEFAULT FALSE,
    creado_en  TIMESTAMP   NOT NULL
);

-- Recuerda el paso 4.7: PostgreSQL no indexa las claves foráneas automáticamente
CREATE INDEX ix_refresh_tokens_usuario_id ON refresh_tokens (usuario_id);
-- Para revocar una familia completa rápidamente
CREATE INDEX ix_refresh_tokens_familia ON refresh_tokens (familia);